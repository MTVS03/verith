"""signals.py 검증용 가짜 수급 DataFrame.

원리: "답을 손으로 미리 알 수 있는 데이터."
  pykrx·네트워크 없이 순수 pandas로, 값은 전부 깔끔한 정수로 짠다.
  그래야 테스트의 기대값(예: 강도 0.20)을 사람이 암산으로 검산할 수 있고,
  테스트가 "구현이 내 정의와 맞는가"를 진짜로 증명하게 된다.

스키마는 signals.py 전제를 그대로 따른다.
  - index: 날짜, **오름차순**(과거 → 최신, 최근이 마지막 행)
  - 컬럼: 개인 / 외국인 / 기관 / 거래대금(종목 총액)
"""

import pandas as pd

_COLUMNS = ["개인", "외국인", "기관", "거래대금"]


def _make(rows: list[list[int]]) -> pd.DataFrame:
    """오름차순 날짜 index를 붙여 DataFrame을 만든다. rows는 과거→최신 순."""
    idx = pd.date_range("2026-06-30", periods=len(rows), freq="B", name="날짜")
    return pd.DataFrame(rows, columns=_COLUMNS, index=idx)


# ── df_foreign_5day_streak ────────────────────────────────
# 외국인: 5일 내내 +40,000 (연속 순매수 5일)
# 개인:   5일 내내 -50,000 (순매도)
# 기관:   +/- 섞임이지만 5일 합은 +50,000 (외국인과 동반 순매수 방향)
# 거래대금: 5일 내내 1,000,000 (평균도 1,000,000)
#
# 손계산 기대값:
#   · 외국인 연속 순매수 = 5일  → signal True (>= 3)
#   · 외국인 강도 = 40,000*5 / 1,000,000 = 200,000 / 1,000,000 = 0.20
#                  → strong True (>= 0.12)
#   · 외국인 5일합 +200,000 & 기관 5일합 +50,000 → alignment "동반매수"
#     (기관 합: 30,000 -10,000 +20,000 -5,000 +15,000 = 50,000)
df_foreign_5day_streak = _make(
    [
        # 개인,     외국인,   기관,     거래대금
        [-50000, 40000, 30000, 1000000],
        [-50000, 40000, -10000, 1000000],
        [-50000, 40000, 20000, 1000000],
        [-50000, 40000, -5000, 1000000],
        [-50000, 40000, 15000, 1000000],
    ]
)


# ── df_zero_value ─────────────────────────────────────────
# 거래대금이 0인 날들. 강도 분모(평균 거래대금)가 0이 되는 방어 로직 검증용.
# 순매수 자체는 있지만(외국인 +40,000 등), 나눌 분모가 0이므로
# 강도는 크래시 없이 0.0으로 안전 후퇴해야 한다.
df_zero_value = _make(
    [
        # 개인,     외국인,   기관,   거래대금
        [-50000, 40000, 10000, 0],
        [-50000, 40000, 10000, 0],
        [-50000, 40000, 10000, 0],
        [-50000, 40000, 10000, 0],
        [-50000, 40000, 10000, 0],
    ]
)


# ── df_foreign_streak_broken ──────────────────────────────
# 외국인: 최신 2일은 순매수(+40,000)지만, 그 직전 날(과거 방향)에
#         순매도(-30,000)가 껴서 연속이 끊긴다.
#
# 손계산 기대(외국인 연속 순매수, 최신부터 거꾸로):
#   row4(+40,000) → 1,  row3(+40,000) → 2,  row2(-30,000) → 멈춤
#   ∴ 연속일수 = 2
#   "왜 2인가": 최신 2일은 순매수지만 그 직전 날 순매도에서 흐름이 끊기므로,
#   '지금 진행 중인 연속'은 딱 2일까지만 인정된다.
df_foreign_streak_broken = _make(
    [
        # 개인,     외국인,   기관,   거래대금
        [-50000, 40000, 10000, 1000000],
        [-50000, 40000, 10000, 1000000],
        [-50000, -30000, 10000, 1000000],  # ← 여기서 연속이 끊긴다
        [-50000, 40000, 10000, 1000000],
        [-50000, 40000, 10000, 1000000],
    ]
)


# ── df_alignment_cross ────────────────────────────────────
# 외국인은 5일 합이 순매수(양수), 기관은 5일 합이 순매도(음수) → 방향 엇갈림.
#
# 손계산 기대(5일 합의 부호):
#   외국인 합 = +20,000 * 5 = +100,000 (양수)
#   기관   합 = -20,000 * 5 = -100,000 (음수)
#   한쪽 양수·한쪽 음수 → 동반 아님 → alignment "엇갈림"
df_alignment_cross = _make(
    [
        # 개인,     외국인,   기관,     거래대금
        [-10000, 20000, -20000, 1000000],
        [-10000, 20000, -20000, 1000000],
        [-10000, 20000, -20000, 1000000],
        [-10000, 20000, -20000, 1000000],
        [-10000, 20000, -20000, 1000000],
    ]
)


# ── df_alignment_cross_reverse ────────────────────────────
# df_alignment_cross 의 부호를 뒤집은 대칭 케이스.
# 외국인이 순매도, 기관이 순매수여서 방향이 반대로 엇갈린다.
# 부호가 반대여도 "동반"이 아니면 똑같이 "엇갈림"이어야 함을 확인한다.
#
# 손계산 기대(5일 합의 부호):
#   외국인 합 = -20,000 * 5 = -100,000 (음수)
#   기관   합 = +20,000 * 5 = +100,000 (양수)
#   한쪽 음수·한쪽 양수 → 동반 아님 → alignment "엇갈림"
df_alignment_cross_reverse = _make(
    [
        # 개인,     외국인,    기관,    거래대금
        [-10000, -20000, 20000, 1000000],
        [-10000, -20000, 20000, 1000000],
        [-10000, -20000, 20000, 1000000],
        [-10000, -20000, 20000, 1000000],
        [-10000, -20000, 20000, 1000000],
    ]
)
